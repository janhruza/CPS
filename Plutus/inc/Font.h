static inline void DrawChar(SDL_Renderer *renderer, int x, int y, char c, SDL_Color col, int scale) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t *glyph = g_Font8x12[c - 32];
    SDL_SetRenderDrawColor(renderer, col.r, col.g, col.b, col.a);
    for (int r = 0; r < FONT_CHAR_H; r++) {
        uint8_t row = glyph[r];
        for (int b = 0; b < FONT_CHAR_W; b++) {
            if (row & (0x80 >> b)) {
                if (scale <= 1) {
                    SDL_RenderDrawPoint(renderer, x + b, y + r);
                } else {
                    SDL_Rect rect = { x + b * scale, y + r * scale, scale, scale };
                    SDL_RenderFillRect(renderer, &rect);
                }
            }
        }
    }
}

static inline void DrawText(SDL_Renderer *renderer, int x, int y, const char *str, SDL_Color col, int scale) {
    if (!str) return;
    int curX = x;
    while (*str) {
        if (*str == '\n') {
            y += (FONT_CHAR_H + 2) * scale;
            curX = x;
        } else {
            DrawChar(renderer, curX, y, *str, col, scale);
            curX += (FONT_CHAR_W) * scale;
        }
        str++;
    }
}

